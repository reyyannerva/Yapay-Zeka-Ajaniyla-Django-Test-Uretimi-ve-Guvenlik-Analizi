    CONSTRAINT ck_reports_format_valid CHECK (format IN ('PDF', 'JSON')),
    CONSTRAINT ck_reports_scope_valid CHECK (scope IN ('FULL', 'PARTIAL')),
    CONSTRAINT ck_reports_file_path_relative
        CHECK (file_path <> '' AND file_path NOT LIKE '/%' AND file_path NOT LIKE '%..%'),
    CONSTRAINT ck_reports_file_size_non_negative CHECK (file_size_bytes >= 0)
);

-- Previous reports of a run, newest first. Also serves the FK.
CREATE INDEX ix_report_run_created
    ON reports (analysis_run_id, created_at DESC);

-- -----------------------------------------------------------------------------
-- 9. llm_calls — one language-model call made through LiteLLM within a run
-- -----------------------------------------------------------------------------
CREATE TABLE llm_calls (
    id                 bigint         GENERATED BY DEFAULT AS IDENTITY,
    analysis_run_id    bigint         NOT NULL,
    generated_test_id  bigint         NULL,
    provider           varchar(20)    NOT NULL,
    model              varchar(100)   NOT NULL,
    purpose            varchar(20)    NOT NULL,
    prompt_tokens      integer        NULL,
    completion_tokens  integer        NULL,
    latency_ms         integer        NULL,
    status             varchar(20)    NOT NULL,
    error_message      varchar(2000)  NULL,
    created_at         timestamptz    NOT NULL DEFAULT now(),

    CONSTRAINT pk_llm_calls PRIMARY KEY (id),
    CONSTRAINT fk_llm_calls_analysis_run
        FOREIGN KEY (analysis_run_id) REFERENCES analysis_runs (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_llm_calls_generated_test
        FOREIGN KEY (generated_test_id) REFERENCES generated_tests (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT ck_llm_calls_provider_valid
        CHECK (provider IN ('GROQ', 'GEMINI', 'OLLAMA')),
    CONSTRAINT ck_llm_calls_model_not_blank CHECK (model <> ''),
    CONSTRAINT ck_llm_calls_purpose_valid CHECK (purpose IN ('GENERATE', 'REPAIR')),
    CONSTRAINT ck_llm_calls_status_valid
        CHECK (status IN ('SUCCESS', 'ERROR', 'QUOTA_EXCEEDED', 'TIMEOUT')),
    CONSTRAINT ck_llm_calls_tokens_non_negative
        CHECK ((prompt_tokens IS NULL OR prompt_tokens >= 0)
           AND (completion_tokens IS NULL OR completion_tokens >= 0)),
    CONSTRAINT ck_llm_calls_latency_non_negative
        CHECK (latency_ms IS NULL OR latency_ms >= 0),
    -- A successful call always reports its token usage.
    CONSTRAINT ck_llm_calls_success_has_tokens
        CHECK (status <> 'SUCCESS'
               OR (prompt_tokens IS NOT NULL AND completion_tokens IS NOT NULL))
);

-- Token and quota metrics of one run in call order. Also serves the FK.
