-- -----------------------------------------------------------------------------
-- 1. projects — a Django/DRF project owned by exactly one user
--    No membership or sharing table exists: a project has a single owner.
-- -----------------------------------------------------------------------------
CREATE TABLE projects (
    id                 bigint        GENERATED BY DEFAULT AS IDENTITY,
    owner_id           integer       NOT NULL,
    name               varchar(150)  NOT NULL,
    description        text          NOT NULL DEFAULT '',
    source_type        varchar(20)   NOT NULL DEFAULT 'ARCHIVE',
    source_archive     varchar(255)  NULL,
    source_directory   varchar(500)  NULL,
    archive_sha256     varchar(64)   NULL,
    validation_status  varchar(20)   NOT NULL DEFAULT 'PENDING',
    validation_report  jsonb         NOT NULL DEFAULT '{}'::jsonb,
    created_at         timestamptz   NOT NULL DEFAULT now(),
    updated_at         timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_projects PRIMARY KEY (id),
    CONSTRAINT fk_projects_owner
        FOREIGN KEY (owner_id) REFERENCES auth_user (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uq_projects_owner_name UNIQUE (owner_id, name),
    CONSTRAINT ck_projects_name_not_blank CHECK (name <> ''),
    CONSTRAINT ck_projects_source_type_valid
        CHECK (source_type IN ('ARCHIVE', 'ALLOWED_DIRECTORY')),
    CONSTRAINT ck_projects_validation_status_valid
        CHECK (validation_status IN ('PENDING', 'VALID', 'INVALID')),
    -- Exactly one source per project: archive columns for ARCHIVE,
    -- source_directory for ALLOWED_DIRECTORY; the other source's columns are NULL.
    CONSTRAINT ck_projects_archive_source_present
        CHECK (source_type <> 'ARCHIVE'
               OR (source_archive IS NOT NULL AND source_archive <> ''
                   AND archive_sha256 IS NOT NULL AND source_directory IS NULL)),
    CONSTRAINT ck_projects_directory_source_present
        CHECK (source_type <> 'ALLOWED_DIRECTORY'
               OR (source_directory IS NOT NULL AND source_directory <> ''
                   AND source_archive IS NULL AND archive_sha256 IS NULL)),
    -- source_archive is a storage-relative key, never an absolute or parent path.
    CONSTRAINT ck_projects_source_archive_relative
        CHECK (source_archive IS NULL
               OR (source_archive NOT LIKE '/%' AND source_archive NOT LIKE '%..%')),
    -- source_directory is relative to the configured allowed root directory.
    CONSTRAINT ck_projects_source_directory_relative
        CHECK (source_directory IS NULL
               OR (source_directory NOT LIKE '/%' AND source_directory NOT LIKE '%..%')),
    CONSTRAINT ck_projects_archive_sha256_format
        CHECK (archive_sha256 IS NULL OR archive_sha256 ~ '^[0-9a-f]{64}$')
);
-- uq_projects_owner_name (owner_id, name) also serves owner-based listing and the
-- owner_id foreign key, so no separate owner_id index is created.

-- -----------------------------------------------------------------------------
-- 2. reference_requirements — independently specified expectations of a project
--    Roles, access rules and deployment expectations are separate rows.
-- -----------------------------------------------------------------------------
CREATE TABLE reference_requirements (
    id                bigint        GENERATED BY DEFAULT AS IDENTITY,
    project_id        bigint        NOT NULL,
    requirement_code  varchar(50)   NOT NULL,
    category          varchar(30)   NOT NULL,
    source            varchar(20)   NOT NULL DEFAULT 'FORM',
    title             varchar(200)  NOT NULL,
    description       text          NOT NULL DEFAULT '',
    expected_result   text          NOT NULL,
    specification     jsonb         NOT NULL DEFAULT '{}'::jsonb,
    is_active         boolean       NOT NULL DEFAULT true,
    revision          integer       NOT NULL DEFAULT 1,
    created_at        timestamptz   NOT NULL DEFAULT now(),
    updated_at        timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_reference_requirements PRIMARY KEY (id),
    CONSTRAINT fk_reference_requirements_project
        FOREIGN KEY (project_id) REFERENCES projects (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uq_reference_requirements_project_code
        UNIQUE (project_id, requirement_code),
    CONSTRAINT ck_reference_requirements_code_format
        CHECK (requirement_code ~ '^[A-Za-z0-9][A-Za-z0-9._-]*$'),
    CONSTRAINT ck_reference_requirements_category_valid
        CHECK (category IN ('ROLE', 'ACCESS_RULE', 'DEPLOY_EXPECTATION')),
    CONSTRAINT ck_reference_requirements_source_valid
        CHECK (source IN ('FORM', 'JSON_UPLOAD')),
    CONSTRAINT ck_reference_requirements_title_not_blank CHECK (title <> ''),
    -- A ROLE row names a role and has no expected result of its own.
    CONSTRAINT ck_reference_requirements_expected_result_not_blank
        CHECK (category = 'ROLE' OR expected_result <> ''),
    CONSTRAINT ck_reference_requirements_revision_positive CHECK (revision >= 1)
);
-- uq_reference_requirements_project_code covers project_id lookups and the FK.

-- -----------------------------------------------------------------------------
-- 3. analysis_runs — one asynchronous processing run of a project
-- -----------------------------------------------------------------------------
CREATE TABLE analysis_runs (
    id                     bigint         GENERATED BY DEFAULT AS IDENTITY,
    project_id             bigint         NOT NULL,
    status                 varchar(20)    NOT NULL DEFAULT 'QUEUED',
    method                 varchar(20)    NOT NULL,
    llm_provider           varchar(20)    NULL,
    llm_model              varchar(100)   NULL,
    fallback_enabled       boolean        NOT NULL DEFAULT true,
    celery_task_id         varchar(255)   NULL,
    requirements_snapshot  jsonb          NOT NULL DEFAULT '[]'::jsonb,
    ast_results            jsonb          NOT NULL DEFAULT '{}'::jsonb,
    processing_metadata    jsonb          NOT NULL DEFAULT '{}'::jsonb,
    coverage_percent       numeric(5,2)   NULL,
    error_code             varchar(50)    NOT NULL DEFAULT '',
    error_message          varchar(2000)  NOT NULL DEFAULT '',
    created_at             timestamptz    NOT NULL DEFAULT now(),
    started_at             timestamptz    NULL,
    finished_at            timestamptz    NULL,
    updated_at             timestamptz    NOT NULL DEFAULT now(),

    CONSTRAINT pk_analysis_runs PRIMARY KEY (id),
    CONSTRAINT fk_analysis_runs_project
        FOREIGN KEY (project_id) REFERENCES projects (id)
        DEFERRABLE INITIALLY DEFERRED,
    -- One run per Celery task id; a duplicate delivery cannot open a second row.
    -- NULL (not yet dispatched) is allowed for any number of rows.
    CONSTRAINT uq_analysis_runs_celery_task_id UNIQUE (celery_task_id),
    CONSTRAINT ck_analysis_runs_status_valid
        CHECK (status IN ('QUEUED', 'ANALYZING', 'GENERATING', 'VALIDATING',
                          'EXECUTING', 'SCANNING', 'COMPLETED', 'FAILED',
                          'CANCELLED')),
    CONSTRAINT ck_analysis_runs_method_valid
        CHECK (method IN ('RULE_BASED', 'DIRECT_LLM', 'HYBRID')),
    CONSTRAINT ck_analysis_runs_llm_provider_valid
        CHECK (llm_provider IS NULL OR llm_provider IN ('GROQ', 'GEMINI', 'OLLAMA')),
    -- RULE_BASED uses no language model; DIRECT_LLM and HYBRID name one.
    CONSTRAINT ck_analysis_runs_llm_settings
        CHECK ((method = 'RULE_BASED' AND llm_provider IS NULL AND llm_model IS NULL)
            OR (method <> 'RULE_BASED' AND llm_provider IS NOT NULL
                AND llm_model IS NOT NULL AND llm_model <> '')),
    CONSTRAINT ck_analysis_runs_coverage_range
        CHECK (coverage_percent IS NULL
               OR (coverage_percent >= 0 AND coverage_percent <= 100)),
    CONSTRAINT ck_analysis_runs_queued_not_started
        CHECK (status <> 'QUEUED' OR started_at IS NULL),
    CONSTRAINT ck_analysis_runs_progress_requires_start
        CHECK (status NOT IN ('ANALYZING', 'GENERATING', 'VALIDATING', 'EXECUTING',
                              'SCANNING', 'COMPLETED')
               OR started_at IS NOT NULL),
    CONSTRAINT ck_analysis_runs_finished_iff_terminal
        CHECK ((status IN ('COMPLETED', 'FAILED', 'CANCELLED') AND finished_at IS NOT NULL)
            OR (status NOT IN ('COMPLETED', 'FAILED', 'CANCELLED') AND finished_at IS NULL)),
    CONSTRAINT ck_analysis_runs_time_order
        CHECK (started_at IS NULL OR finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_analysis_runs_failure_has_error_code
        CHECK (status <> 'FAILED' OR error_code <> '')
);

-- Project history page: runs of one project, newest first. Also serves the FK.
CREATE INDEX ix_analysisrun_project_created
    ON analysis_runs (project_id, created_at DESC);
-- Worker monitoring and stale-run detection: runs in a given status by age.
CREATE INDEX ix_analysisrun_status_created
    ON analysis_runs (status, created_at);
-- At most one non-terminal run per project; blocks duplicate submissions.
CREATE UNIQUE INDEX uq_analysis_runs_one_active_per_project
    ON analysis_runs (project_id)
    WHERE status IN ('QUEUED', 'ANALYZING', 'GENERATING', 'VALIDATING',
                     'EXECUTING', 'SCANNING');

-- -----------------------------------------------------------------------------
-- 4. endpoints — an HTTP endpoint found by AST analysis within one run
--    analysis_runs.ast_results keeps the raw analyser output; this table holds
--    one normalised row per (path, method). HEAD and OPTIONS are out of scope.
-- -----------------------------------------------------------------------------
CREATE TABLE endpoints (
    id                  bigint        GENERATED BY DEFAULT AS IDENTITY,
    analysis_run_id     bigint        NOT NULL,
    path                varchar(500)  NOT NULL,
    http_method         varchar(10)   NOT NULL,
    view_name           varchar(255)  NOT NULL,
    auth_type           varchar(50)   NOT NULL DEFAULT '',
    permission_classes  jsonb         NOT NULL DEFAULT '[]'::jsonb,
    is_supported        boolean       NOT NULL DEFAULT true,
    unsupported_reason  varchar(50)   NULL,
    created_at          timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_endpoints PRIMARY KEY (id),
    CONSTRAINT fk_endpoints_analysis_run
        FOREIGN KEY (analysis_run_id) REFERENCES analysis_runs (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uq_endpoints_run_path_method
        UNIQUE (analysis_run_id, path, http_method),
    CONSTRAINT ck_endpoints_path_not_blank CHECK (path <> ''),
    CONSTRAINT ck_endpoints_http_method_valid
        CHECK (http_method IN ('GET', 'POST', 'PUT', 'PATCH', 'DELETE')),
    CONSTRAINT ck_endpoints_unsupported_reason_valid
        CHECK (unsupported_reason IS NULL
               OR unsupported_reason IN ('DYNAMIC_ROUTE', 'CUSTOM_PERMISSION')),
    CONSTRAINT ck_endpoints_unsupported_has_reason
        CHECK (is_supported OR unsupported_reason IS NOT NULL)
);
-- uq_endpoints_run_path_method covers analysis_run_id lookups and the FK.

-- -----------------------------------------------------------------------------
-- 5. generated_tests — a Pytest test produced within one analysis run
-- -----------------------------------------------------------------------------
CREATE TABLE generated_tests (
    id                   bigint        GENERATED BY DEFAULT AS IDENTITY,
    analysis_run_id      bigint        NOT NULL,
    endpoint_id          bigint        NULL,
    test_module          varchar(150)  NOT NULL,
    test_name            varchar(150)  NOT NULL,
    generation_method    varchar(20)   NOT NULL,
    requirement_code     varchar(50)   NOT NULL DEFAULT '',
    role                 varchar(50)   NOT NULL DEFAULT '',
    expected_status      smallint      NULL,
    is_security_test     boolean       NOT NULL DEFAULT false,
    source_code          text          NOT NULL,
    code_sha256          varchar(64)   NOT NULL,
    validation_status    varchar(20)   NOT NULL DEFAULT 'PENDING',
    validation_errors    jsonb         NOT NULL DEFAULT '[]'::jsonb,
    repair_count         smallint      NOT NULL DEFAULT 0,
    generation_metadata  jsonb         NOT NULL DEFAULT '{}'::jsonb,
    created_at           timestamptz   NOT NULL DEFAULT now(),
    updated_at           timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT pk_generated_tests PRIMARY KEY (id),
    CONSTRAINT fk_generated_tests_analysis_run
        FOREIGN KEY (analysis_run_id) REFERENCES analysis_runs (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_generated_tests_endpoint
        FOREIGN KEY (endpoint_id) REFERENCES endpoints (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uq_generated_tests_run_module_name
        UNIQUE (analysis_run_id, test_module, test_name),
    -- Module names are bare file names: no directories, no traversal.
    CONSTRAINT ck_generated_tests_module_format
        CHECK (test_module ~ '^test_[A-Za-z0-9_]+\.py$'),
    CONSTRAINT ck_generated_tests_name_format
        CHECK (test_name ~ '^test_[A-Za-z0-9_]+$'),
    CONSTRAINT ck_generated_tests_method_valid
        CHECK (generation_method IN ('LLM', 'RULE_BASED')),
    CONSTRAINT ck_generated_tests_expected_status_range
        CHECK (expected_status IS NULL OR expected_status BETWEEN 100 AND 599),
    CONSTRAINT ck_generated_tests_validation_status_valid
        CHECK (validation_status IN ('PENDING', 'VALID', 'INVALID_SYNTAX',
                                     'REJECTED_POLICY')),
    -- A test is repaired at most once (data_dictionary.md 9.3).
    CONSTRAINT ck_generated_tests_repair_count_range
        CHECK (repair_count BETWEEN 0 AND 1),
    CONSTRAINT ck_generated_tests_code_sha256_format
        CHECK (code_sha256 ~ '^[0-9a-f]{64}$')
);
-- uq_generated_tests_run_module_name covers analysis_run_id lookups and the FK.
CREATE INDEX ix_gentest_endpoint ON generated_tests (endpoint_id);

-- -----------------------------------------------------------------------------
-- 6. test_executions — one execution attempt of a generated test
--    Ownership: test_executions -> generated_tests -> analysis_runs -> projects.
--    There is intentionally no analysis_run_id column here.
-- -----------------------------------------------------------------------------
CREATE TABLE test_executions (
    id                 bigint          GENERATED BY DEFAULT AS IDENTITY,
    generated_test_id  bigint          NOT NULL,
    attempt_number     integer         NOT NULL,
    status             varchar(20)     NOT NULL DEFAULT 'QUEUED',
    observed_status    smallint        NULL,
    error_type         varchar(20)     NULL,
    error_origin       varchar(20)     NULL,
    started_at         timestamptz     NULL,
    finished_at        timestamptz     NULL,
    duration_ms        integer         NULL,
    output_excerpt     varchar(10000)  NOT NULL DEFAULT '',
    error_summary      varchar(2000)   NOT NULL DEFAULT '',
    result_details     jsonb           NOT NULL DEFAULT '{}'::jsonb,
    created_at         timestamptz     NOT NULL DEFAULT now(),

    CONSTRAINT pk_test_executions PRIMARY KEY (id),
    CONSTRAINT fk_test_executions_generated_test
        FOREIGN KEY (generated_test_id) REFERENCES generated_tests (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uq_test_executions_test_attempt
        UNIQUE (generated_test_id, attempt_number),
    CONSTRAINT ck_test_executions_status_valid
        CHECK (status IN ('QUEUED', 'RUNNING', 'PASS', 'FAIL', 'TECHNICAL_ERROR',
                          'STOPPED', 'NOT_RUN')),
    CONSTRAINT ck_test_executions_observed_status_range
        CHECK (observed_status IS NULL OR observed_status BETWEEN 100 AND 599),
    CONSTRAINT ck_test_executions_error_type_valid
        CHECK (error_type IS NULL
               OR error_type IN ('IMPORT', 'FIXTURE', 'SYNTAX', 'TIMEOUT', 'OOM', 'OTHER')),
    CONSTRAINT ck_test_executions_error_origin_valid
        CHECK (error_origin IS NULL
               OR error_origin IN ('TEST_CODE', 'TARGET_APP', 'INFRASTRUCTURE')),
    CONSTRAINT ck_test_executions_technical_error_has_type
        CHECK (status <> 'TECHNICAL_ERROR' OR error_type IS NOT NULL),
    CONSTRAINT ck_test_executions_attempt_positive CHECK (attempt_number >= 1),
    CONSTRAINT ck_test_executions_duration_non_negative
        CHECK (duration_ms IS NULL OR duration_ms >= 0),
    CONSTRAINT ck_test_executions_queued_not_started
        CHECK (status <> 'QUEUED' OR (started_at IS NULL AND finished_at IS NULL)),
    CONSTRAINT ck_test_executions_not_run_not_started
        CHECK (status <> 'NOT_RUN' OR (started_at IS NULL AND finished_at IS NULL)),
    CONSTRAINT ck_test_executions_running_started
        CHECK (status <> 'RUNNING' OR (started_at IS NOT NULL AND finished_at IS NULL)),
    CONSTRAINT ck_test_executions_terminal_finished
        CHECK (status NOT IN ('PASS', 'FAIL', 'TECHNICAL_ERROR', 'STOPPED')
               OR finished_at IS NOT NULL),
    -- PASS and FAIL are pytest outcomes, so the test must have started.
    CONSTRAINT ck_test_executions_outcome_requires_start
        CHECK (status NOT IN ('PASS', 'FAIL') OR started_at IS NOT NULL),
    CONSTRAINT ck_test_executions_time_order
        CHECK (started_at IS NULL OR finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_test_executions_duration_requires_finish
        CHECK (duration_ms IS NULL OR finished_at IS NOT NULL)
);
-- uq_test_executions_test_attempt covers generated_test_id lookups and the FK.

-- -----------------------------------------------------------------------------
-- 7. security_findings — a security observation produced by one analysis run
-- -----------------------------------------------------------------------------
CREATE TABLE security_findings (
    id                  bigint         GENERATED BY DEFAULT AS IDENTITY,
    analysis_run_id     bigint         NOT NULL,
    test_execution_id   bigint         NULL,
    endpoint_id         bigint         NULL,
    source              varchar(20)    NOT NULL,
    rule_id             varchar(100)   NOT NULL,
    severity            varchar(10)    NOT NULL,
    classification      varchar(20)    NOT NULL DEFAULT 'POSSIBLE',
    title               varchar(255)   NOT NULL,
    description         text           NOT NULL DEFAULT '',
    file_path           varchar(500)   NOT NULL DEFAULT '',
    line_number         integer        NULL,
    evidence_excerpt    varchar(1000)  NOT NULL DEFAULT '',
    recommendation_key  varchar(50)    NULL,
    details             jsonb          NOT NULL DEFAULT '{}'::jsonb,
    fingerprint         varchar(64)    NOT NULL,
    created_at          timestamptz    NOT NULL DEFAULT now(),

    CONSTRAINT pk_security_findings PRIMARY KEY (id),
    CONSTRAINT fk_security_findings_analysis_run
        FOREIGN KEY (analysis_run_id) REFERENCES analysis_runs (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_security_findings_test_execution
        FOREIGN KEY (test_execution_id) REFERENCES test_executions (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT fk_security_findings_endpoint
        FOREIGN KEY (endpoint_id) REFERENCES endpoints (id)
        DEFERRABLE INITIALLY DEFERRED,
    -- Makes finding writes idempotent under duplicate task delivery.
    CONSTRAINT uq_security_findings_run_fingerprint
        UNIQUE (analysis_run_id, fingerprint),
    CONSTRAINT ck_security_findings_source_valid
        CHECK (source IN ('AUTH_TEST', 'BANDIT', 'CHECK_DEPLOY')),
    CONSTRAINT ck_security_findings_severity_valid
        CHECK (severity IN ('HIGH', 'MEDIUM', 'LOW', 'UNKNOWN')),
    CONSTRAINT ck_security_findings_classification_valid
        CHECK (classification IN ('VERIFIED', 'POSSIBLE', 'UNCERTAIN')),
    CONSTRAINT ck_security_findings_rule_id_not_blank CHECK (rule_id <> ''),
    CONSTRAINT ck_security_findings_title_not_blank CHECK (title <> ''),
    -- file_path is relative to the analysed project root.
    CONSTRAINT ck_security_findings_file_path_relative
        CHECK (file_path NOT LIKE '/%' AND file_path NOT LIKE '%..%'),
    CONSTRAINT ck_security_findings_line_number_positive
        CHECK (line_number IS NULL OR line_number >= 1),
    CONSTRAINT ck_security_findings_fingerprint_format
        CHECK (fingerprint ~ '^[0-9a-f]{64}$')
);

-- Report view: findings of one run filtered or grouped by severity.
CREATE INDEX ix_finding_run_severity
    ON security_findings (analysis_run_id, severity);
CREATE INDEX ix_finding_execution ON security_findings (test_execution_id);
CREATE INDEX ix_finding_endpoint ON security_findings (endpoint_id);

