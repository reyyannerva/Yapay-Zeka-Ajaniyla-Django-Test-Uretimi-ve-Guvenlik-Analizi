-- Status of this file
--   This is a REFERENCE DDL. The running application manages its schema through
--   Django migrations generated from django_models.py. Do not apply this file to
--   a database that is already managed by Django migrations. Its purposes are:
--     * a reviewable, tool-independent statement of the relational contract,
--     * the source for the ER diagram,
--     * bootstrapping a disposable database for review or experiments.
--
-- Assumptions
--   A1. User accounts live in Django's built-in auth_user table (django.contrib.auth),
--       whose primary key is "id integer" because the auth app uses AutoField.
--       This file does NOT define auth_user; it must already exist (run
--       `python manage.py migrate auth` first). If the project switches to a custom
--       AUTH_USER_MODEL, projects.owner_id must reference that table and take the
--       type of its primary key.
--   A2. Foreign keys are declared DEFERRABLE INITIALLY DEFERRED without an
--       ON DELETE action, which is how Django migrations create them on PostgreSQL.
--       Deletion behaviour is performed by the Django ORM: on_delete=CASCADE for
--       the mandatory ownership keys, on_delete=SET_NULL for the optional cross
--       references (generated_tests.endpoint_id, security_findings.test_execution_id,
--       security_findings.endpoint_id, llm_calls.generated_test_id).
--       A raw SQL DELETE on a parent row that still has children is therefore
--       rejected at commit time. See data_dictionary.md section 12.
--   A3. Column DEFAULT clauses document the canonical default value. Django's
--       `default=` is applied by the ORM in Python and is not written to the
--       database by migrations. Both describe the same value.
--   A4. updated_at columns are maintained by the ORM (auto_now). No trigger is
--       defined, so raw SQL updates must set updated_at explicitly.
--   A5. No table stores passwords, JWT tokens, LLM API keys or other secrets.
--   A6. Framework-managed tables are not defined here: auth_user (django.contrib.auth)
--       and the django-axes login-lockout tables (axes_accessattempt, axes_accesslog,
--       axes_accessfailurelog, axes_accessattemptexpiration). The axes tables store
--       the username as text and have no foreign key to any table in this file.
--       Password reset uses Django's token mechanism and needs no table.
--   A7. Controlled values are stored in UPPER CASE (e.g. 'QUEUED'). Lower-case
--       spellings in diagrams and documents (e.g. queued) denote the same values.
-- =============================================================================

